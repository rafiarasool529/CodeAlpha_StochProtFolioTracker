# Stock Portfolio Tracker

# Stock prices dictionary
stock_prices = {
    "AAPL": 180,
    "TSLA": 250,
    "GOOGL": 140,
    "MSFT": 400,
    "AMZN": 170
}

# Welcome message
print("================================")
print("     STOCK PORTFOLIO TRACKER")
print("================================")

# Empty dictionary for user stocks
portfolio = {}

# Take number of stocks
num_stocks = int(input("How many stocks do you want to add? "))

# Loop to take stock details
for i in range(num_stocks):

    stock_name = input("\nEnter stock symbol (AAPL, TSLA, GOOGL, MSFT, AMZN): ").upper()

    if stock_name in stock_prices:

        quantity = int(input("Enter quantity: "))

        portfolio[stock_name] = portfolio.get(stock_name, 0) + quantity

    else:
        print("Stock not available!")

# Calculate total investment
total_investment = 0

print("\n========== PORTFOLIO DETAILS ==========")

for stock, quantity in portfolio.items():

    price = stock_prices[stock]
    investment = price * quantity

    total_investment += investment

    print(stock, "| Quantity:", quantity,
          "| Price:", price,
          "| Investment:", investment)

# Display total
print("\nTotal Investment:", total_investment)

# Save result in text file
with open("portfolio_report.txt", "w") as file:

    file.write("STOCK PORTFOLIO REPORT\n")
    file.write("======================\n")

    for stock, quantity in portfolio.items():

        price = stock_prices[stock]
        investment = price * quantity

        file.write(
            f"{stock} | Quantity: {quantity} | Price: {price} | Investment: {investment}\n"
        )

    file.write(f"\nTotal Investment: {total_investment}")

print("\nPortfolio report saved successfully!")